/* Generate lib/hyperloglog/bias.shen. See docs/hyperloglog.md for the command. */
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

enum { samples = 176, sample_steps = 32, intervals = 72, knots_per_block = 12, scale = 1 << 20 };

static uint64_t sample_hash(uint64_t *state)
{
    uint64_t x = (*state += UINT64_C(0x9e3779b97f4a7c15));
    x = (x ^ (x >> 30)) * UINT64_C(0xbf58476d1ce4e5b9);
    x = (x ^ (x >> 27)) * UINT64_C(0x94d049bb133111eb);
    return x ^ (x >> 31);
}

static double alpha(int p, int m)
{
    if (p == 4) return 0.673;
    if (p == 5) return 0.697;
    if (p == 6) return 0.709;
    return 0.7213 / (1 + 1.079 / m);
}

static void calibrate(int p)
{
    int m = 1 << p;
    int trials = p <= 10 ? 8192 : p <= 14 ? 2048 : 384;
    int counts[samples + 1] = {0};
    double mean[samples + 1] = {0}, weights[62];
    uint8_t *registers = malloc((size_t)m);
    if (!registers) exit(EXIT_FAILURE);

    for (int r = 0; r < 62; r++) weights[r] = ldexp(1.0, -r);
    int num = 1;
    for (int i = 1; i <= samples; i++) {
        int n = i * m / sample_steps;
        if (n > counts[num - 1]) counts[num++] = n;
    }

    uint64_t seed = UINT64_C(0x43da08f4292cc297) + (uint64_t)p;
    double a = alpha(p, m);
    for (int trial = 0; trial < trials; trial++) {
        memset(registers, 0, (size_t)m);
        mean[0] += a;
        double mass = m;
        int n = 0;
        for (int point = 1; point < num; point++) {
            while (n < counts[point]) {
                uint64_t h = sample_hash(&seed);
                size_t bucket = (size_t)(h >> (64 - p));
                int rank = 1 + __builtin_clzll((h << p) | (UINT64_C(1) << (p - 1)));
                if (rank > registers[bucket]) {
                    mass += weights[rank] - weights[registers[bucket]];
                    registers[bucket] = (uint8_t)rank;
                }
                n++;
            }
            mean[point] += a * m / mass;
        }
    }
    free(registers);
    for (int i = 0; i < num; i++) mean[i] /= trials;

    /* Resample the measured bias at uniform raw-estimate multiples of m. */
    int hi = 1;
    for (int i = 0; i <= intervals; i++) {
        if (i % knots_per_block == 0) {
            if (i != 0) puts("\"");
            printf("  %d %d -> \"", p, i / knots_per_block);
        }
        double raw = 0.5 + (double)i / 16;
        while (hi < num - 1 && mean[hi] < raw) hi++;
        double fraction = raw <= mean[0] ? 0 : (raw - mean[hi - 1]) / (mean[hi] - mean[hi - 1]);
        double lo_bias = mean[hi - 1] - (double)counts[hi - 1] / m;
        double hi_bias = mean[hi] - (double)counts[hi] / m;
        long packed = lround(scale * (1 + lo_bias + fraction * (hi_bias - lo_bias)));
        if (mean[num - 1] < raw || packed < 0 || packed >= (1 << 24)) exit(EXIT_FAILURE);
        printf("%06lx", (unsigned long)packed);
    }
    puts("\"\n");
}

int main(void)
{
    puts("\\\\ Generated by tools/hyperloglog-calibrate.c.");
    puts("\\\\ Knots from raw/m = 0.5 to 5 in steps of 1/16, each encoded as");
    puts("\\\\ six hex digits for round((1 + bias/m) * 2^20).");
    puts("(shen.x.namespace hyperloglog");
    puts("(define bias-block");
    puts("  {fixnum --> fixnum --> string}");
    for (int p = 4; p <= 18; p++) calibrate(p);
    puts("  _ _ -> (error \"hyperloglog: no calibration for this precision\"))");
    puts(")");
}
